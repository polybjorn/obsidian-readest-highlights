import esbuild from "esbuild";
import process from "process";
import { builtinModules } from 'node:module';
import { copyFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { pluginDir } from "./scripts/plugin-dir.mjs";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
const target = pluginDir();

const install = {
	name: "install",
	setup(build) {
		build.onEnd((result) => {
			if (!target || result.errors.length) return;
			mkdirSync(target, { recursive: true });
			for (const file of ["main.js", "manifest.json", "styles.css"]) copyFileSync(file, join(target, file));
			console.log(`Copied the build to ${target}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [install],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
